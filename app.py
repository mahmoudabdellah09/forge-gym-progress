@app.route('/api/foods/search', methods=['GET'])
def search_foods():
    raw_query = request.args.get('q', '').strip()[:100]
    norm_query = normalize_arabic(raw_query)

    conn = get_db_connection()
    if norm_query:
        # Normalize both sides in Python so Arabic variants also match names and aliases.
        candidates = conn.execute('''
            SELECT id, name, category, type, level, description, swap, aliases
            FROM foods
        ''').fetchall()
        foods = [
            food for food in candidates
            if any(norm_query in normalize_arabic(food[field] or '')
                   for field in ('name', 'category', 'description', 'aliases'))
        ]
        foods.sort(key=lambda food: {
            'allow': 1, 'daily': 2, 'weekly': 3, 'monthly': 4
        }.get(food['type'], 5))
