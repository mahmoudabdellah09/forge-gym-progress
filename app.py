def normalize_arabic(text):
    """تنظيف وتوحيد الأحرف العربية للبحث العامي والتلقائي"""
    if not text:
        return ""
    text = text.lower().strip()
    replacements = {
        'أ': 'ا', 'إ': 'ا', 'آ': 'ا',
        'ة': 'ه',
        'ى': 'ي',
        'ؤ': 'و', 'ئ': 'ي'
    }
    for search, replace in replacements.items():
        text = text.replace(search, replace)
    return text

